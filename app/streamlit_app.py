def _page_cscan(session: Session | None) -> None:
    """Page 2: C-scan view with indication overlays and A-scan drilldown."""
    st.header("2 C-scan view")
    st.caption(
        "Peak amplitude C-scan map over the bar surface. "
        "Circles (o) indicate rules-based indications; crosses (x) mark ML flags. "
        "Select an indication to inspect its A-scan, gates, and DAC curve."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    st.pyplot(cscan_figure(session))
    if not session.items:
        st.info("No indications detected.")
        return

    labels = [
        f"#{i}: {it.category} ({it.source}) ax={it.indication.axial_mm:.1f}mm"
        if it.indication
        else f"#{i}: {it.category} ({it.source}) ax={session.scan.axial_mm[it.ml.axial_idx]:.1f}mm"
        for i, it in enumerate(session.items)
    ]
    sel = st.selectbox(
        "Pick indication to inspect A-scan:",
        range(len(session.items)),
        format_func=lambda i: labels[i],
    )
    item = session.items[sel]
    ia = item.indication.axial_idx if item.indication else item.ml.axial_idx
    ja = item.indication.angle_idx if item.indication else item.ml.angle_idx
    st.pyplot(ascan_figure(session, ia, ja))


def _page_indication_list(session: Session | None) -> None:
    """Page 3: Ranked table of indications."""
    st.header("3 Indication list")
    st.caption(
        "Ranked indication triage list. Rejectable indications and uncertain findings "
        "are placed at the top for priority inspector review. "
        "Amplitude is relative to the DAC curve (100% = reference reflector)."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    rows = []
    for i, it in enumerate(session.items):
        amp = f"{it.indication.amplitude_pct:.1f}%" if it.indication else "-"
        snr = f"{it.indication.snr_db:.1f} dB" if it.indication else "-"
        ml_score = f"{it.ml.score:.2f}" if it.ml else "-"
        unc = f"{it.ml.uncertainty:.2f}" if it.ml else "-"
        reasons = "; ".join(it.indication.reasons) if it.indication else "ML detection"
        rows.append(
            {
                "#": i,
                "Source": it.source,
                "Category": it.category,
                "Amp (% DAC)": amp,
                "SNR": snr,
                "ML Score": ml_score,
                "Uncertainty": unc,
                "Reasons": reasons,
            }
        )
    st.dataframe(pd.DataFrame(rows), use_container_width=True)


def _page_data_quality(session: Session | None) -> None:
    """Page 4: Watchdog data-quality faults and re-scan recommendation."""
    st.header("4 Data quality")
    st.caption(
        "The data-quality watchdog verifies couplant stability, interface echo amplitude, "
        "and back-wall retention. If signal quality falls below acceptance limits, "
        "a re-scan is recommended."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    quality = session.evaluation.quality
    if quality.rescan_recommended:
        st.error("🚨 Re-scan recommended: Data-quality watchdog detected faults.")
    else:
        st.success("✅ Quality OK: Couplant and back-wall retention within limits.")

    if quality.faults:
        rows = [
            {
                "Fault kind": f.kind,
                "Axial (mm)": f"{f.axial_mm[0]:.1f} – {f.axial_mm[1]:.1f}",
                "Angle (deg)": f"{f.angle_deg[0]:.1f}° – {f.angle_deg[1]:.1f}°",
                "A-scans affected": f.n_ascans,
            }
            for f in quality.faults
        ]
        st.table(pd.DataFrame(rows))
    else:
        st.info("Zero quality faults detected.")


