"""UTriage offline inspector review app (project plan Phase 6).

Advisory only: UTriage never accepts or rejects a part. Every decision
belongs to the certified inspector.

NOTE: Streamlit must run offline without telemetry.
Set `gatherUsageStats = false` in `.streamlit/config.toml`.
"""

from __future__ import annotations

import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

_SRC = str(Path(__file__).resolve().parents[1] / "src")
if _SRC not in sys.path:
    sys.path.insert(0, _SRC)
if "utriage" in sys.modules:
    _pkg_dir = str(Path(_SRC) / "utriage")
    if _pkg_dir not in sys.modules["utriage"].__path__:
        del sys.modules["utriage"]

import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

from utriage.app_logic import (  # noqa: E402
    Session,
    ascan_figure,
    cscan_figure,
    load_session,
    record_decision,
)
from utriage.report.html import ReportInput, render_report  # noqa: E402

DEFAULT_SAMPLE = Path("data/samples/ti64/bar_0000.npz")
DEFAULT_MODEL = Path("models/window_net.pt")

st.set_page_config(
    page_title="UTriage — Ultrasonic Bar Inspection Review",
    layout="wide",
    initial_sidebar_state="expanded",
)


def _render_banners(session: Session | None) -> None:
    """Display mandatory advisory banner, synthetic label, and placeholder warnings."""
    st.info(
        "Advisory tool - decisions by certified inspector "
        "(UTriage never accepts or rejects a part automatically)."
    )
    if session is not None and session.synthetic:
        st.warning("Synthetic data (Generated by immersion UT simulator)")
    if session is not None and session.evaluation.placeholder_limits:
        st.error(
            "PLACEHOLDER acceptance limits: These limits are unverified against "
            "AMS-STD-2154 / ASTM E2375 (UNVERIFIED - Ruri to check)."
        )


def _get_session() -> Session | None:
    """Retrieve or initialize inspection session."""
    if "session" not in st.session_state:
        if DEFAULT_SAMPLE.is_file():
            st.session_state.session = load_session(DEFAULT_SAMPLE, DEFAULT_MODEL)
        else:
            st.session_state.session = None
    return st.session_state.session


def _handle_sample_load(session: Session | None) -> None:
    """Handle loading the committed sample bar scan."""
    if st.button("Load sample bar", type="primary") or session is None:
        if DEFAULT_SAMPLE.is_file():
            st.session_state.session = load_session(DEFAULT_SAMPLE, DEFAULT_MODEL)
            st.success("Loaded sample bar: data/samples/ti64/bar_0000.npz")


def _handle_upload_load() -> None:
    """Handle user file upload for .npz or .csv scans."""
    uploaded = st.file_uploader("Upload .npz or .csv scan file", type=["npz", "csv"])
    if uploaded is not None:
        tmp_dir = Path(tempfile.gettempdir()) / "utriage_uploads"
        tmp_dir.mkdir(parents=True, exist_ok=True)
        tmp_file = tmp_dir / uploaded.name
        tmp_file.write_bytes(uploaded.getbuffer())
        if st.button("Process uploaded scan", type="primary"):
            st.session_state.session = load_session(tmp_file, DEFAULT_MODEL)
            st.success(f"Loaded {uploaded.name}")


def _page_load_scan(session: Session | None) -> None:
    """Page 1: Load scan file (.npz or .csv) or sample bar."""
    st.header("1 Load scan")
    st.caption(
        "Load an ultrasonic scan file (.npz or .csv) or select the sample Ti-6Al-4V bar. "
        "All processing runs offline on this computer."
    )
    choice = st.radio(
        "Choose scan source:",
        ["Sample: data/samples/ti64/bar_0000.npz", "Upload file (.npz or .csv)"],
    )
    if choice.startswith("Sample"):
        _handle_sample_load(session)
    else:
        _handle_upload_load()

    cur = st.session_state.get("session")
    if cur is not None:
        st.divider()
        st.write(
            f"**Current bar:** `{cur.bar_id}` | "
            f"**Material:** `{cur.scan.spec.material.name}` | "
            f"**Diameter:** `{cur.scan.spec.diameter_mm:.1f} mm` | "
            f"**Length:** `{cur.scan.spec.length_mm:.1f} mm`"
        )


def _page_cscan(session: Session | None) -> None:
    """Page 2: C-scan view with indication overlays and A-scan drilldown."""
    st.header("2 C-scan view")
    st.caption(
        "Peak amplitude C-scan map over the bar surface. "
        "Circles (o) indicate rules-based indications; crosses (x) mark ML flags. "
        "Select an indication to inspect its A-scan, gates, and DAC curve."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    st.pyplot(cscan_figure(session))
    if not session.items:
        st.info("No indications detected.")
        return

    labels = [
        f"#{i}: {it.category} ({it.source}) ax={it.indication.axial_mm:.1f}mm"
        if it.indication
        else f"#{i}: {it.category} ({it.source}) ax={session.scan.axial_mm[it.ml.axial_idx]:.1f}mm"
        for i, it in enumerate(session.items)
    ]
    sel = st.selectbox(
        "Pick indication to inspect A-scan:",
        range(len(session.items)),
        format_func=lambda i: labels[i],
    )
    item = session.items[sel]
    ia = item.indication.axial_idx if item.indication else item.ml.axial_idx
    ja = item.indication.angle_idx if item.indication else item.ml.angle_idx
    st.pyplot(ascan_figure(session, ia, ja))


def _page_indication_list(session: Session | None) -> None:
    """Page 3: Ranked table of indications."""
    st.header("3 Indication list")
    st.caption(
        "Ranked indication triage list. Rejectable indications and uncertain findings "
        "are placed at the top for priority inspector review. "
        "Amplitude is relative to the DAC curve (100% = reference reflector)."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    rows = []
    for i, it in enumerate(session.items):
        amp = f"{it.indication.amplitude_pct:.1f}%" if it.indication else "-"
        snr = f"{it.indication.snr_db:.1f} dB" if it.indication else "-"
        ml_score = f"{it.ml.score:.2f}" if it.ml else "-"
        unc = f"{it.ml.uncertainty:.2f}" if it.ml else "-"
        reasons = "; ".join(it.indication.reasons) if it.indication else "ML detection"
        rows.append(
            {
                "#": i,
                "Source": it.source,
                "Category": it.category,
                "Amp (% DAC)": amp,
                "SNR": snr,
                "ML Score": ml_score,
                "Uncertainty": unc,
                "Reasons": reasons,
            }
        )
    st.dataframe(pd.DataFrame(rows), use_container_width=True)


def _page_data_quality(session: Session | None) -> None:
    """Page 4: Watchdog data-quality faults and re-scan recommendation."""
    st.header("4 Data quality")
    st.caption(
        "The data-quality watchdog verifies couplant stability, interface echo amplitude, "
        "and back-wall retention. If signal quality falls below acceptance limits, "
        "a re-scan is recommended."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    quality = session.evaluation.quality
    if quality.rescan_recommended:
        st.error("🚨 Re-scan recommended: Data-quality watchdog detected faults.")
    else:
        st.success("✅ Quality OK: Couplant and back-wall retention within limits.")

    if quality.faults:
        rows = [
            {
                "Fault kind": f.kind,
                "Axial (mm)": f"{f.axial_mm[0]:.1f} – {f.axial_mm[1]:.1f}",
                "Angle (deg)": f"{f.angle_deg[0]:.1f}° – {f.angle_deg[1]:.1f}°",
                "A-scans affected": f.n_ascans,
            }
            for f in quality.faults
        ]
        st.table(pd.DataFrame(rows))
    else:
        st.info("Zero quality faults detected.")


def _render_decision_history(session: Session) -> None:
    """Render table of decisions recorded in current session."""
    if session.decisions:
        st.subheader("Recorded decisions in this session")
        d_rows = [
            {
                "Item #": d.item_index,
                "Decision": d.decision,
                "Inspector": d.inspector,
                "Comment": d.comment,
            }
            for d in session.decisions
        ]
        st.table(pd.DataFrame(d_rows))


def _page_decision_log(session: Session | None) -> None:
    """Page 5: Inspector decision recording (accept/reject/re-scan)."""
    st.header("5 Decision log")
    st.caption(
        "Record inspector disposition for each indication into the audit log (logs/audit_log.csv). "
        "All decisions require certified inspector identification."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    insp = st.text_input("Inspector name / ID", value=st.session_state.get("inspector", ""))
    if insp:
        st.session_state.inspector = insp

    if session.items:
        opts = [f"#{i}: {it.category} ({it.source})" for i, it in enumerate(session.items)]
        idx = st.selectbox(
            "Select indication:", range(len(session.items)), format_func=lambda i: opts[i]
        )
        dec = st.radio("Decision:", ["accepted", "rejected", "rescan"], horizontal=True)
        cmt = st.text_input("Inspector comment:", value="")
        if st.button("Record decision", type="primary"):
            if not insp.strip():
                st.error("Inspector name/ID is required.")
            else:
                record_decision(session, idx, dec, cmt, insp.strip(), Path("logs/audit_log.csv"))
                st.success(f"Recorded '{dec}' for indication #{idx} in logs/audit_log.csv")

    _render_decision_history(session)


def _page_report(session: Session | None) -> None:
    """Page 6: Printable inspection report generation."""
    st.header("6 Report")
    st.caption(
        "Generate a formal inspection report pre-filled with data quality findings, "
        "indication triage, and inspector decisions."
    )
    if session is None:
        st.info("Please load a scan first.")
        return
    now_str = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    rep_inp = ReportInput(
        bar_id=session.bar_id or "bar_0000",
        evaluation=session.evaluation,
        items=session.items,
        decisions=session.decisions,
        synthetic=session.synthetic,
        generated_at=now_str,
    )
    rep_html = render_report(rep_inp)
    st.download_button(
        "Download Inspection Report (HTML)",
        data=rep_html,
        file_name=f"inspection_report_{session.bar_id or 'bar'}.html",
        mime="text/html",
    )
    st.markdown(
        "**Print instructions:** Open the downloaded HTML report in any web browser and use "
        "**Ctrl+P** (or Cmd+P) -> **Save as PDF** for formal Level II certification archiving."
    )


PAGE_HANDLERS = {
    "1 Load scan": _page_load_scan,
    "2 C-scan view": _page_cscan,
    "3 Indication list": _page_indication_list,
    "4 Data quality": _page_data_quality,
    "5 Decision log": _page_decision_log,
    "6 Report": _page_report,
}


def main() -> None:
    """Main Streamlit app router."""
    session = _get_session()
    _render_banners(session)
    pages = list(PAGE_HANDLERS.keys())
    page = st.sidebar.radio("Navigation", pages)
    handler = PAGE_HANDLERS.get(page)
    if handler is not None:
        handler(session)


if __name__ == "__main__" or True:  # Streamlit script entrypoint
    main()
