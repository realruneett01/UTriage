def upload_target(tmp_dir: Path, name: str) -> Path:
    """Resolve upload destination ensuring containment inside tmp_dir."""
    if any(sep in name for sep in ("..", "/", "\\")):
        raise ValueError(f"Unsafe filename containing path traversal: {name}")
    clean_name = safe_filename(name)
    resolved_dir = tmp_dir.resolve()
    target = (resolved_dir / clean_name).resolve()
    if resolved_dir not in target.parents:
        raise ValueError(f"Target path outside directory: {target}")
    return target


def _pair_scan(p: Path, json_stems: set[str]) -> tuple[Path | None, str | None]:
    """Classify scan candidate path as loadable or error message."""
    suf = p.suffix.lower()
    if suf == ".csv":
        return p, None
    if suf == ".npz" and p.stem in json_stems:
        return p, None
    if suf == ".npz":
        msg = (
            f"{p.name}: no matching {p.stem}.json found automatically - "
            "upload the .npz together with its .json file."
        )
        return None, msg
    return None, None


def _loadable_scans(saved: list[Path]) -> tuple[list[Path], list[str]]:
    """Partition saved files into loadable scan paths and missing-pair messages."""
    json_stems = {p.stem for p in saved if p.suffix.lower() == ".json"}
    loadable: list[Path] = []
    errors: list[str] = []
    for p in saved:
        scan_path, err_msg = _pair_scan(p, json_stems)
        if scan_path is not None:
            loadable.append(scan_path)
        if err_msg is not None:
            errors.append(err_msg)
    return loadable, errors


def _save_upload(up: Any, tmp_dir: Path) -> Path | None:
    """Save an uploaded file safely to tmp_dir."""
    if up.size > MAX_SCAN_BYTES:
        st.error(f"{up.name}: size exceeds maximum limit of {MAX_SCAN_BYTES} bytes.")
        return None
    try:
        target = upload_target(tmp_dir, up.name)
    except ValueError as exc:
        st.error(f"Invalid upload filename: {exc}")
        return None
    if tmp_dir not in target.parents:
        st.error("Upload path outside temporary directory.")
        return None
    target.write_bytes(up.getbuffer())
    return target


def _save_uploaded_files(uploaded: list[Any], tmp_dir: Path) -> list[Path]:
    """Save valid uploaded files into tmp_dir."""
    saved: list[Path] = []
    for up in uploaded:
        target = _save_upload(up, tmp_dir)
        if target is not None:
            saved.append(target)
    return saved


def _candidate_json_match(cand: Path, npz_resolved: Path, target_hash: str) -> Path | None:
    """Return candidate sibling JSON if hash matches and not self."""
    if cand.resolve() == npz_resolved or not cand.is_file():
        return None
    sibling = cand.with_suffix(".json")
    if sibling.is_file() and hashlib.sha256(cand.read_bytes()).hexdigest() == target_hash:
        return sibling
    return None


def _search_root(root: Path, name: str, npz_resolved: Path, target_hash: str) -> Path | None:
    """Search single root for sibling JSON matching target hash."""
    if not root.exists():
        return None
    for cand in root.rglob(name):
        match = _candidate_json_match(cand, npz_resolved, target_hash)
        if match is not None:
            return match
    return None


def _find_matching_json(npz: Path, roots: Sequence[Path]) -> Path | None:
    """Find local sibling JSON matching the uploaded NPZ by SHA-256 hash."""
    if not npz.is_file():
        return None
    target_hash = hashlib.sha256(npz.read_bytes()).hexdigest()
    npz_resolved = npz.resolve()
    for root in roots:
        matched = _search_root(root, npz.name, npz_resolved, target_hash)
        if matched is not None:
            return matched
    return None


def _pair_single_npz(
    npz: Path, roots: Sequence[Path], json_stems: set[str]
) -> tuple[Path, str] | None:
    """Find matching JSON and copy to NPZ directory if needed."""
    if npz.suffix.lower() != ".npz" or npz.stem in json_stems:
        return None
    src = _find_matching_json(npz, roots)
    if src is None:
        return None
    dst = npz.parent / f"{npz.stem}.json"
    shutil.copyfile(src, dst)
    note = f"{npz.name}: matching {npz.stem}.json found automatically in {src.parent}"
    return dst, note


def _auto_pair(saved: list[Path], roots: Sequence[Path]) -> tuple[list[Path], list[str]]:
    """Automatically discover and copy sibling JSON for NPZ scans without JSON."""
    out_saved = list(saved)
    notes: list[str] = []
    json_stems = {p.stem for p in saved if p.suffix.lower() == ".json"}
    for p in saved:
        res = _pair_single_npz(p, roots, json_stems)
        if res is not None:
            dst, note = res
            out_saved.append(dst)
            notes.append(note)
            json_stems.add(p.stem)
    return out_saved, notes


def _choose_scan(loadable: list[Path]) -> Path:
    """Select scan to process when multiple candidates exist."""
    if len(loadable) > 1:
        names = [p.name for p in loadable]
        idx = names.index(st.selectbox("Scan to process", names))
        return loadable[idx]
    return loadable[0]


def _process_scan(scan_path: Path) -> None:
    """Load session from chosen scan path and report status."""
    try:
        st.session_state.session = load_session(scan_path, DEFAULT_MODEL)
        st.success(f"Loaded {scan_path.name}")
    except (FileNotFoundError, ValueError, KeyError, OSError) as exc:
        st.error(f"Could not load {scan_path.name}: {exc}")


def _handle_upload_load() -> None:
    """Handle user file upload for .npz, .json, and .csv scans."""
    uploaded = st.file_uploader(
        "Upload scan files (.npz with its matching .json, or .csv)",
        type=["npz", "json", "csv"],
        accept_multiple_files=True,
    )
    st.caption(
        "Upload a .npz scan; its .json is found automatically when the scan comes from "
        "this machine's data folder. Otherwise upload both."
    )
    if not uploaded:
        return
    tmp_dir = (Path(tempfile.gettempdir()) / "utriage_uploads").resolve()
    tmp_dir.mkdir(parents=True, exist_ok=True)
    saved = _save_uploaded_files(uploaded, tmp_dir)
    saved, notes = _auto_pair(saved, SCAN_SEARCH_ROOTS)
    for note in notes:
        st.info(note)
    loadable, errors = _loadable_scans(saved)
    for err in errors:
        st.error(err)
    if not loadable:
        return
    chosen = _choose_scan(loadable)
    if st.button("Process uploaded scan", type="primary"):
        _process_scan(chosen)


