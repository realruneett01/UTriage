"""Physics-aware data augmentation for ultrasonic A-scans and B-scans.

Synthetic data generation: all virtual flaw implantations and augmentations
produce synthetic data for training and evaluating ultrasonic triage models.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class AugmentConfig:
    """Configuration for physics-aware ultrasonic data augmentation."""

    gain_db: float = 3.0
    max_shift: int = 4
    noise_std: float = 0.02
    pulse_stretch: float = 0.1
    p: float = 0.5


def gain_change(
    x: np.ndarray,
    rng: np.random.Generator,
    gain_db: float = 3.0,
    *,
    gain_val: float | None = None,
) -> np.ndarray:
    """Apply random gain scaling in dB with amplitude scale 10**(g/20).

    Outputs are Synthetic data when applied to simulated scans.
    """
    db = abs(gain_db)
    if db == 0.0 and gain_val is None:
        return x.copy()
    g = float(rng.uniform(-db, db)) if gain_val is None else float(gain_val)
    scale = 10.0 ** (g / 20.0)
    return (x * scale).astype(x.dtype)


def time_shift(
    x: np.ndarray,
    rng: np.random.Generator,
    max_shift: int = 4,
    *,
    shift: int | None = None,
) -> np.ndarray:
    """Integer roll along the last axis with zero fill, not wrap.

    Outputs are Synthetic data when applied to simulated scans.
    """
    s = (
        int(rng.integers(-max_shift, max_shift, endpoint=True))
        if shift is None and max_shift > 0
        else (0 if shift is None else int(shift))
    )
    length = x.shape[-1]
    if s == 0:
        return x.copy()
    out = np.zeros_like(x)
    if abs(s) >= length:
        return out
    if s > 0:
        out[..., s:] = x[..., :-s]
    else:
        out[..., :s] = x[..., -s:]
    return out


def add_noise(
    x: np.ndarray,
    rng: np.random.Generator,
    noise_std: float = 0.02,
) -> np.ndarray:
    """Add Gaussian noise with std relative to signal RMS.

    Outputs are Synthetic data when applied to simulated scans.
    """
    if noise_std <= 0.0:
        return x.copy()
    rms = float(np.sqrt(np.mean(np.square(x, dtype=np.float64))))
    if rms == 0.0:
        return x.copy()
    noise = rng.normal(loc=0.0, scale=noise_std * rms, size=x.shape)
    return (x + noise).astype(x.dtype)


def _resample_1d(
    row: np.ndarray,
    orig_c: np.ndarray,
    new_c: np.ndarray,
    length: int,
) -> np.ndarray:
    """Resample 1D signal with np.interp and crop or zero-pad to length."""
    res = np.interp(new_c, orig_c, row)
    if len(res) >= length:
        return res[:length].astype(row.dtype)
    return np.pad(res, (0, length - len(res)), mode="constant").astype(row.dtype)


def pulse_shape_change(
    x: np.ndarray,
    rng: np.random.Generator,
    pulse_stretch: float = 0.1,
    *,
    factor: float | None = None,
) -> np.ndarray:
    """Resample along last axis by factor 1+-pulse_stretch with np.interp, crop/pad.

    Outputs are Synthetic data when applied to simulated scans.
    """
    length = x.shape[-1]
    if length <= 1 or (pulse_stretch <= 0.0 and factor is None):
        return x.copy()
    f = (
        float(rng.uniform(1.0 - pulse_stretch, 1.0 + pulse_stretch))
        if factor is None
        else float(factor)
    )
    new_len = max(1, int(round(length * max(f, 1e-4))))
    if new_len == length:
        return x.copy()
    orig_c = np.linspace(0.0, float(length - 1), length)
    new_c = np.linspace(0.0, float(length - 1), new_len)
    x_flat = x.reshape(-1, length)
    res = np.stack(
        [_resample_1d(row, orig_c, new_c, length) for row in x_flat],
        axis=0,
    )
    return res.reshape(x.shape)


def _build_slices(
    clean_shape: tuple[int, ...],
    patch_shape: tuple[int, ...],
    pos_seq: tuple[int, ...],
) -> tuple[tuple[slice, ...], tuple[slice, ...]]:
    """Build matching clean and patch slice tuples for implantation."""
    c_slices: list[slice] = []
    p_slices: list[slice] = []
    for d in range(len(clean_shape)):
        pos_d = pos_seq[d]
        c_start = max(0, pos_d)
        c_end = min(clean_shape[d], pos_d + patch_shape[d])
        p_start = max(0, -pos_d)
        p_end = p_start + max(0, c_end - c_start)
        c_slices.append(slice(c_start, c_end))
        p_slices.append(slice(p_start, p_end))
    return tuple(c_slices), tuple(p_slices)


def implant_virtual_flaw(
    clean: np.ndarray,
    flaw_patch: np.ndarray,
    position: int | tuple[int, ...],
    scale: float = 1.0,
) -> np.ndarray:
    """Implant a virtual flaw patch onto an unflawed background at position.

    The unflawed background is copied, never modified in-place.
    Outputs generated by virtual flaw implantation are Synthetic data.
    """
    out = clean.copy()
    pos_seq = (
        (int(position),)
        if isinstance(position, (int, np.integer))
        else tuple(int(p) for p in position)
    )
    if len(pos_seq) < clean.ndim:
        pos_seq = (0,) * (clean.ndim - len(pos_seq)) + pos_seq

    patch = np.asarray(flaw_patch) * scale
    while patch.ndim < clean.ndim:
        patch = np.expand_dims(patch, axis=0)

    c_slices, p_slices = _build_slices(clean.shape, patch.shape, pos_seq)
    out[c_slices] += patch[p_slices].astype(clean.dtype)
    return out


def augment(
    x: np.ndarray,
    cfg: AugmentConfig,
    rng: np.random.Generator,
) -> np.ndarray:
    """Apply gain, shift, noise, and pulse shape change independently with prob p.

    Outputs are Synthetic data when applied to simulated scans.
    """
    out = x.copy()
    if rng.random() < cfg.p:
        out = gain_change(out, rng, cfg.gain_db)
    if rng.random() < cfg.p:
        out = time_shift(out, rng, cfg.max_shift)
    if rng.random() < cfg.p:
        out = add_noise(out, rng, cfg.noise_std)
    if rng.random() < cfg.p:
        out = pulse_shape_change(out, rng, cfg.pulse_stretch)
    return out
